function prepareCounterImageData() {
  for (let i = 0; i < numCounterImages; i++) {
    let x1 = counterImageCorner.x + counterImagePadding;
    let y1 = counterImageCorner.y + counterImagePadding + (counterImageHeight + counterImagePadding)*i;
    let x2 = x1 + counterImageWidth;
    let y2 = y1 + counterImageHeight;
    let c1 = new Coord(x1, y1);
    let c2 = new Coord(x2, y2);
    counterImageBboxArray.push(new BoundingBox(c1, c2));
  }
}


function prepareScreenTransitionBboxDictionaryData() {
  Object.keys(screen_transition_bbox_dictionary_data).forEach((from) => {
    screenTransitionBboxDictionary[from] = {}
    Object.keys(screen_transition_bbox_dictionary_data[from]).forEach((to) => {
      screenTransitionBboxDictionary[from][to] = [];
      let bboxdata_array = screen_transition_bbox_dictionary_data[from][to];
      bboxdata_array.forEach((bboxdata) => {
        screenTransitionBboxDictionary[from][to].push(new BoundingBox(bboxdata.c1, bboxdata.c2));
      })
    })
  })
  
  //createInternetScreenTransitions();
}

function createInternetScreenTransitions() {
  webpageScreenNames.forEach((webpageName) => {
    if (!screenTransitionBboxDictionary[webpageName]) {
      screenTransitionBboxDictionary[webpageName] = {};
    }
    screenTransitionBboxDictionary[webpageName]["home"] = homeButtonBoxes;
    screenTransitionBboxDictionary[webpageName]["wiki"] = wikiButtonBoxes;
    screenTransitionBboxDictionary[webpageName]["paint"] = paintButtonBoxes;
    Object.keys(screenTransitionBboxDictionary).forEach((from) => {
      Object.keys(screenTransitionBboxDictionary[from]).forEach((to) => {
        if (to == webpageName) {
          screenTransitionBboxDictionary[webpageName][from] = backButtonBoxes;
        }
      })
    });
  })
}


function prepareToolItemData() {
  for (let i = 0; i < numToolItems; i++) {
      let x1 = toolItemGridPadding + (toolItemWidth + toolItemPadding)*i;
      let x2 = x1 + toolItemWidth;
      let y1 = toolItemGridPadding ;
      let y2 = y1 + toolItemHeight;
      let c1 = new Coord(x1, y1);
      let c2 = new Coord(x2, y2);
      toolItemBboxArray.push(new BoundingBox(c1, c2));
  }
}


function potArrayDataToArray(potArrayData) {
  let potArray = []
  potArrayData.forEach((potData) => {
    let pot = Pot.fromJson(potData);
    pot.seed_type = Seed.fromJson(pot.seed_type)
    pot.bbox = BoundingBox.fromJson(pot.bbox);
    potArray.push(pot);
  })
  return potArray;
}


